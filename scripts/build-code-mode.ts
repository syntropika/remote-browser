/** Build the checked-in JavaScript helpers embedded by the standalone Rust host. */
import { build } from "bun";

const bundle = await build({
  entrypoints: ["src/host/code/page.ts"],
  outdir: "src/host/code",
  naming: "page.js",
  format: "iife",
  target: "browser",
  minify: false,
  banner: "// Generated by bun run build:code-mode; edit page.ts instead.",
});
if (!bundle.success) {
  for (const log of bundle.logs) {
    console.error(log);
  }
  throw new Error("Code mode helpers did not build");
}
