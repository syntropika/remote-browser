/** Builds the dashboard the host embeds: Bun bundles the script, Tailwind writes the stylesheet. */
import { $ } from "bun";

const bundle = await Bun.build({
  entrypoints: ["ui/main.tsx"],
  outdir: "src/host/ui",
  naming: "app.js",
  format: "iife",
  target: "browser",
  minify: true,
  define: { "process.env.NODE_ENV": '"production"' },
  banner: "// Generated by bun run build; edit the TypeScript sources in ui/ instead.",
});

if (!bundle.success) {
  for (const log of bundle.logs) {
    console.error(log);
  }
  throw new Error("The dashboard script did not build.");
}

await $`bun node_modules/@tailwindcss/cli/dist/index.mjs --input ui/theme.css --output src/host/ui/app.css --minify`;
