import { execFile } from "node:child_process";
import path from "node:path";
import { promisify } from "node:util";

import { build } from "esbuild";

const command = promisify(execFile);
for (const [entry, filename] of [
  ["ui/servo-api-keys.ts", "api-keys.js"],
  ["ui/servo-features.ts", "features.js"],
  ["ui/servo-downloads.ts", "../engine/src/download_bridge.js"],
]) {
  const output = path.normalize(`native/servo/ui/${filename}`);
  await build({
    entryPoints: [entry],
    outfile: output,
    bundle: true,
    format: "iife",
    target: "es2022",
    minify: true,
    banner: {
      js: "// Generated by npm run build:servo-ui; edit the corresponding TypeScript UI sources.",
    },
  });
  await command(process.execPath, ["node_modules/oxfmt/bin/oxfmt", output]);
}
