import { execFile } from "node:child_process";
import { promisify } from "node:util";

import { build } from "esbuild";

const command = promisify(execFile);
const output = "native/servo/ui/api-keys.js";
await build({
  entryPoints: ["ui/servo-api-keys.ts"],
  outfile: output,
  bundle: true,
  format: "iife",
  target: "es2022",
  minify: true,
  banner: {
    js: "// Generated by npm run build:servo-ui; edit ui/api-keys.ts and ui/servo-api-keys.ts.",
  },
});
await command(process.execPath, ["node_modules/oxfmt/bin/oxfmt", output]);
